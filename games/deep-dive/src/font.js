export function textW(s, sc = 1) { return s.length ? (s.length * 4 - 1) * sc : 0; }
export function text(ctx, s, x, y, col = '#fff', sc = 1, align = 'left', shadow = '#000') {
  s = String(s).toUpperCase();
  let w = textW(s, sc);
  if (align === 'center') x -= Math.floor(w / 2); else if (align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  const pass = (ox, oy, c) => {
    ctx.fillStyle = c;
    for (let k = 0; k < s.length; k++) {
      const g = G[s[k]] || G['?'];
      for (let p = 0; p < 15; p++) if (g.charCodeAt(p) === 49) ctx.fillRect(x + ox + (k * 4 + p % 3) * sc, y + oy + ((p / 3) | 0) * sc, sc, sc);
    }
  };
  if (shadow) pass(sc, sc, shadow);
  pass(0, 0, col);
  return w;
}
