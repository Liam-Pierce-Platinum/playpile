function glyph(ch) {
  return G[ch] || G['?'];
}

export function textWidth(str, s = 1, tracking = 1) {
  str = String(str).toUpperCase();
  let w = 0;
  for (const ch of str) w += (glyph(ch)[0].length + tracking) * s;
  return w - tracking * s;
}

// Draws into a view. `shadow` puts a 1px drop under it -- Stardew UI text always
// has one, and it is what keeps light text readable over a bright sky.
export function text(v, str, x, y, col, opts = {}) {
  const s = opts.scale || 1;
  const tracking = opts.tracking == null ? 1 : opts.tracking;
  str = String(str).toUpperCase();
  x = Math.round(x); y = Math.round(y);

  if (opts.align === 'center') x -= Math.round(textWidth(str, s, tracking) / 2);
  else if (opts.align === 'right') x -= textWidth(str, s, tracking);

  if (opts.outline) {
    for (const d of [[-s, 0], [s, 0], [0, -s], [0, s], [-s, -s], [s, -s], [-s, s], [s, s]]) {
      draw(v, str, x + d[0], y + d[1], opts.outline, s, tracking);
    }
  }
  if (opts.shadow) draw(v, str, x + s, y + s, opts.shadow, s, tracking);
  draw(v, str, x, y, col, s, tracking);
  return textWidth(str, s, tracking);
}

function draw(v, str, x, y, col, s, tracking) {
  const g = v.g;
  g.fillStyle = col;
  let cx = x;
  for (const ch of str) {
    const rows = glyph(ch);
    const w = rows[0].length;
    if (ch !== ' ') {
      for (let ry = 0; ry < rows.length; ry++) {
        const row = rows[ry];
        let run = 0;
        for (let rx = 0; rx <= w; rx++) {
          if (rx < w && row[rx] === '#') { run++; continue; }
          if (run) { g.fillRect(cx + (rx - run) * s, y + ry * s, run * s, s); run = 0; }
        }
      }
    }
    cx += (w + tracking) * s;
  }
}
